
export const morningNotificationAiPrompt = (userData) => `
**Задача:**
Сгенерируй уникальное мотивационное утреннее сообщение для пользователя с именем ${userData.firstname}.

**Контекст о пользователе:**
- Список активных привычек: ${userData.habitsText}

**Требования к сообщению:**
- **Формат:** 1-3 коротких предложения.
- **Тон:** Энергичный, поддерживающий, дружелюбный.
- **Структура:**
    1. **Приветствие и вовлечение:** Обратись по имени, используй 1-2 утренних эмодзи (🌞, 🌅, ☀️, 🌄).
    2. **Анализ и фокус:** Бегло проанализируй список привычек и выдели ОДНУ ключевую мысль или самый важный элемент для каждой привычки. Не перечисляй всё подряд.
    3. **Практический совет:** Дай одно конкретное, микро-действие для легкого старта, связанное с его привычками.
- **Уникальность:** Каждый день сообщение должно быть разным (разные эмодзи, формулировки, советы).

**Примеры стиля:**
- «Доброе утро, ${userData.firstname} 🌞 Чашка Иван-чая + 10 стр. книги — мягкий запуск. Прогулка без телефона зарядит фокус 🚶‍♂️»
- «Утро на вашей стороне, ${userData.firstname}. Стакан воды + 15 мин чтения 📖 — и короткая прогулка без экрана. Поехали 💪»
- «Сегодня начните с Иван-чая 🌿 и 20-минутной ходьбы без телефона — дыхание и голова скажут спасибо.»

**Сгенерируй сообщение на основе этих данных:**
- Имя: ${userData.firstname}
- Привычки: ${userData.habitsText}
`;

